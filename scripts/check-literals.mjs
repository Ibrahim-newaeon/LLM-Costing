#!/usr/bin/env node
// /scripts/check-literals.mjs
//
// Standing rule 1 — "zero hardcoded rates" — turned into a gate.
//
// §A12's first checklist item is a grep: "finds zero numeric price literals, tile
// constants, or tokens-per-second values in /packages and /apps". A grep run by
// hand proves the state of the tree on the day someone remembers to run it. This
// runs in CI, and it fails on a number nobody wrote down a reason for.
//
//   node scripts/check-literals.mjs            # report
//   node scripts/check-literals.mjs --check    # exit 1 on any drift  (CI)
//   node scripts/check-literals.mjs --write    # re-record the allowlist
//
// THE RULE: every numeric literal in a non-test source under packages/*/src must
// be either structural (0, 1, 2 — indices, arity, tier numbers) or recorded in
// scripts/literal-allowlist.json with a reason. Counts are matched exactly, so a
// second occurrence of an already-allowed value is also drift.
//
// Keyed on (file, value) and NOT on line number, deliberately: a gate that churns
// on every edit above it gets regenerated without being read, and an allowlist
// nobody reads is not a gate.
//
// ⚠️ WHAT THIS IS NOT. It is a lexer, not a parser — TypeScript 7 is the native
// port and ships no JS compiler API, and a parser dependency for a lint of our own
// source is not worth its supply chain. It strips comments and string/template
// bodies with a small state machine and then matches numbers. Its failure
// direction is over-reporting: an unusual construct produces a spurious entry that
// someone annotates, never a rate that slips through silently.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';

const ALLOWLIST = 'scripts/literal-allowlist.json';
const STRUCTURAL = new Set(['0', '1', '2']);

/** Blank out comments and string/template bodies, preserving every line break. */
function scrub(src) {
  let out = '';
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    const d = src[i + 1];
    if (c === '/' && d === '/') {
      while (i < n && src[i] !== '\n') { out += ' '; i++; }
      continue;
    }
    if (c === '/' && d === '*') {
      while (i < n && !(src[i] === '*' && src[i + 1] === '/')) { out += src[i] === '\n' ? '\n' : ' '; i++; }
      out += '  '; i += 2;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') {
      const quote = c;
      out += ' '; i++;
      while (i < n) {
        if (src[i] === '\\') { out += '  '; i += 2; continue; }
        if (src[i] === quote) { out += ' '; i++; break; }
        out += src[i] === '\n' ? '\n' : ' ';
        i++;
      }
      continue;
    }
    out += c; i++;
  }
  return out;
}

// A number not preceded by an identifier character or a dot, so `x2` and `a.5`
// and the digits inside an identifier never match.
const NUMBER = /(?<![\w.$])(\d[\d_]*(?:\.\d[\d_]*)?(?:e[+-]?\d+)?)/gi;

function scan() {
  const files = execSync("git ls-files 'packages/*/src/*.ts'", { encoding: 'utf8' })
    .split('\n')
    .filter((f) => f && !f.endsWith('.test.ts'));

  /** @type {Map<string, {count: number, lines: number[]}>} */
  const found = new Map();
  for (const file of files) {
    const raw = readFileSync(file, 'utf8');
    const lines = scrub(raw).split('\n');
    lines.forEach((line, idx) => {
      for (const m of line.matchAll(NUMBER)) {
        const value = m[1].replaceAll('_', '');
        if (STRUCTURAL.has(value)) continue;
        const key = `${file}|${value}`;
        const e = found.get(key) ?? { count: 0, lines: [] };
        e.count++;
        e.lines.push(idx + 1);
        found.set(key, e);
      }
    });
  }
  return found;
}

const found = scan();
const mode = process.argv.includes('--write') ? 'write'
  : process.argv.includes('--check') ? 'check' : 'report';

const existing = existsSync(ALLOWLIST) ? JSON.parse(readFileSync(ALLOWLIST, 'utf8')) : { entries: {} };

if (mode === 'write') {
  const entries = {};
  for (const [key, { count }] of [...found].sort(([a], [b]) => a.localeCompare(b))) {
    entries[key] = { count, reason: existing.entries?.[key]?.reason ?? 'TODO: why this number is not a rate' };
  }
  writeFileSync(ALLOWLIST, JSON.stringify({
    // Keep the human-written header. A regeneration that replaced it with this
    // default did so silently on 2026-09-09; the allowlist's own explanation of
    // itself is not build output.
    $comment: existing.$comment ?? 'Generated by scripts/check-literals.mjs --write. Every entry needs a reason a human wrote. A number with no reason is a rate waiting to be found.',
    entries,
  }, null, 2) + '\n');
  console.log(`wrote ${ALLOWLIST} — ${Object.keys(entries).length} entries`);
  process.exit(0);
}

const problems = [];
for (const [key, { count, lines }] of found) {
  const e = existing.entries?.[key];
  const [file, value] = key.split('|');
  if (!e) {
    problems.push(`UNRECORDED  ${file}:${lines.join(',')}  ${value}\n            Give it a name and a reason, or take the number from the registry.`);
  } else if (e.count !== count) {
    problems.push(`COUNT DRIFT ${file}  ${value}  allowlist says ${e.count}, found ${count} (lines ${lines.join(',')})`);
  } else if (!e.reason || e.reason.startsWith('TODO')) {
    problems.push(`NO REASON   ${file}  ${value}  — the allowlist entry exists but nobody said why.`);
  }
}
for (const key of Object.keys(existing.entries ?? {})) {
  if (!found.has(key)) {
    const [file, value] = key.split('|');
    problems.push(`STALE       ${file}  ${value}  is allowlisted and no longer present. Remove it — a list that only grows stops being a record.`);
  }
}

if (problems.length === 0) {
  console.log(`no unrecorded numeric literals — ${found.size} allowlisted (rule 1) ✓`);
  process.exit(0);
}
console.error(`\nrule 1 — numeric literals with no recorded reason:\n`);
for (const p of problems) console.error('  ' + p);
console.error(`\n${problems.length} problem(s). Fix the code, or run --write and write a real reason.\n`);
process.exit(mode === 'check' ? 1 : 0);
